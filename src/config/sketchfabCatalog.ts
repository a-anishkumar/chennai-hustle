export const SKETCHFAB_BY_ID: Record<string, SketchfabCatalogEntry> = Object.fromEntries(
  SKETCHFAB_CATALOG.map((e) => [e.id, e])
);

const manifestData = sketchfabManifest as {
  available: Record<string, boolean>;
  resolvedPaths?: Record<string, string>;
};

export function getSketchfabModelRelPath(id: string): string | null {
  if (!manifestData.available[id] || !SKETCHFAB_BY_ID[id]) return null;
  return manifestData.resolvedPaths?.[id] || SKETCHFAB_BY_ID[id].localPath;
}

export function isSketchfabModelDownloaded(id: string): boolean {
  return Boolean(getSketchfabModelRelPath(id));
}

